/**
 * Мостик «человек сам сделал свайп назад» → жест-подсказка.
 *
 * Зачем модуль, а не проп. Знает о свайпе `components/AndroidEdgeSwipeBack.tsx`
 * — обёртка всего `<Stack>` в корневом layout'е. Подсказку показывает
 * `SwipeBackHintHost`, её сосед по тому же layout'у. Прокидывать колбэк между
 * ними через props пришлось бы сквозь `_layout.tsx`, который и так самый
 * перегруженный файл приложения; контекст ради одного вызова — лишний
 * провайдер на всё дерево.
 *
 * Регистратор один: хост в приложении ровно один. Второй вызов перетирает
 * первый намеренно — так при hot-reload не остаётся висеть колбэк мёртвого
 * компонента.
 *
 * iOS сюда не приходит: там свайп везёт нативный стек, и отличить его от
 * нажатия стрелки в шапке нечем. См. комментарий в SwipeBackHintHost.
 */
let handler: (() => void) | null = null;

/** Подписать подсказку. Возвращает отписку — звать из useEffect. */
export function setSwipeBackPerformedHandler(fn: () => void): () => void {
  handler = fn;
  return () => {
    if (handler === fn) handler = null;
  };
}

/** Свайп «назад» доведён до конца. Безопасно звать, когда подсказки нет. */
export function notifySwipeBackPerformed(): void {
  handler?.();
}
