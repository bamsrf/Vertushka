/**
 * introStore — «интро маскота отыграло» как глобальный флаг.
 *
 * Зачем: `MascotIntro` живёт в корневом layout и держит `introDone` локальным
 * useState'ом, а сканер (центральная вкладка) монтируется под интро сразу на
 * холодном старте и тут же поднимает камеру. На Android это плохо дважды:
 * открытие камеры конкурирует с декодером за ролик на бюджетном устройстве
 * (интро «грузится наполовину»), и в статус-баре загорается индикатор
 * камеры, пока на экране ещё заставка. Сканер читает флаг отсюда и на Android
 * не включает камеру, пока интро не снято. iOS ветка не гейтится — там всё
 * работало как есть.
 *
 * Флаг взводится один раз за процесс и назад не сбрасывается: интро играет
 * ровно раз за холодный старт (см. `app/_layout.tsx`).
 */
import { create } from 'zustand';

interface IntroState {
  done: boolean;
  markDone: () => void;
}

export const useIntroStore = create<IntroState>((set) => ({
  done: false,
  markDone: () => set({ done: true }),
}));
