/**
 * Потолок СИСТЕМНОГО font-scale (настройка «Размер текста» в iOS/Android).
 *
 * Это ПОТОЛОК, а не коэффициент: при 100% масштабе визуал не меняется.
 *
 * История значения:
 *   1.15 (08.09.2026) — вынужденный компромисс. Вёрстка держала высоты кнопок
 *     и полей жёстко (`height: 56`), поэтому подпись при росте шрифта не
 *     влезала и ломалась пополам («Добавит / ь»). Резать масштаб было
 *     единственным способом не показывать сломанный экран.
 *   1.30 — после того, как высоты стали `minHeight` + вертикальный паддинг, а
 *     подписи получили `flexShrink`. Теперь крупный текст растит контейнер, а
 *     не обрезается в нём, и 15% потолка стали неоправданно жадными: человек
 *     с плохим зрением ставит 130–200% и должен получать заметно более
 *     крупный текст.
 *
 * Выше 1.3 не поднимаем: дальше начинают конфликтовать двухколоночные сетки
 * (карточки релизов) — для них нужна отдельная раскладка в одну колонку.
 *
 * Живёт отдельным файлом без импортов из react-native: его читает
 * `scaledText.tsx`, который подставляется вместо RN через metro-alias, и
 * любой импорт `react-native` отсюда замкнул бы цикл модулей.
 */
export const MAX_FONT_SCALE = 1.3;
